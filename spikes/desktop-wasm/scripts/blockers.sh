#!/usr/bin/env bash
# Ticket 0206: who pulls each blocker, and what did the wasm attempt even reach.
# Usage: blockers.sh <apps/desktop dir> <out dir>
set -uo pipefail
d="${1:?usage: blockers.sh <apps/desktop dir> <out dir>}"
out="${2:?usage: blockers.sh <apps/desktop dir> <out dir>}"
mkdir -p "$out"
cd "$d"

blockers="mio getrandom rustls mac_address filedescriptor open notify-rust wasm_thread cef-dll-sys tattoy-wezterm-term cef gpui-pre gpui-pre-platform"

{
  echo "# apps/desktop dependency graph (ticket 0206)"
  echo "# generated by:"
  echo "#   cd apps/desktop"
  echo "#   cargo tree -e no-dev | grep -c ' '                                   # tree lines"
  echo "#   cargo tree -e no-dev --prefix none | awk 'NF{print \$1\" \"\$2}' | sort -u   # name@version"
  echo "# command output follows (blank line between the two)"
  cargo tree -e no-dev 2>/dev/null | grep -c ' '
  echo
  cargo tree -e no-dev --prefix none 2>/dev/null | awk 'NF{print $1" "$2}' | sort -u
} > "$out/deps-all.txt" 2>&1

for b in $blockers; do
  echo "===== $b =====" > "$out/tree-$b.txt"
  # -i prints the reverse tree: who depends on it.
  cargo tree -e no-dev -i "$b" --invert 2>&1 | head -40 >> "$out/tree-$b.txt"
done
cat "$out"/tree-*.txt | grep -E '^=====|^\S*$' | head -0
ls -la "$out"
