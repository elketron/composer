//! Generates the Dart models of the protocol (`apps/composer_protocol`) from its JSON Schema.
//!
//!   cargo run -p composer-protocol --features schema --bin dartgen            # write
//!   cargo run -p composer-protocol --features schema --bin dartgen -- --check # CI: fail if stale
//!
//! Structs become classes, string enums Dart enums, tagged enums (`#[serde(tag = ...)]`)
//! sealed classes with one subclass per variant plus an `…Unknown` one (forward compatible).
//! It also writes JSON fixtures of sample messages that the Dart tests round-trip.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use composer_protocol::http::{
    AgentSummary, AppMessage, ChangedFile, PageExcerpt, PageResponse, PipelineSummary, ProjectDiff,
    ProjectOverview, ProjectSummary, PutPageRequest, PutPageResponse, SearchHit, ServerInfo,
    SiteSummary, StageState, StageSummary, TicketBranchSummary, TicketReview, WorkSummary,
};
use composer_protocol::*;
use serde_json::{Map, Value, json};

/// Structs that embed a tagged enum with `#[serde(flatten)]`: (struct, field, enum).
const FLATTENED: [(&str, &str, &str); 1] = [("ClientRequest", "command", "ClientCommand")];

fn main() {
    let check = std::env::args().any(|a| a == "--check");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../apps/composer_protocol");
    let mut files: Vec<(PathBuf, String)> = vec![(
        root.join("lib/src/protocol.g.dart"),
        generate(&definitions()),
    )];
    for (name, samples) in fixtures() {
        let text = serde_json::to_string_pretty(&samples).expect("serializes") + "\n";
        files.push((root.join(format!("test/fixtures/{name}.json")), text));
    }

    let mut stale = Vec::new();
    for (path, content) in &files {
        if std::fs::read_to_string(path).ok().as_deref() != Some(content) {
            stale.push(path.display().to_string());
            if !check {
                std::fs::create_dir_all(path.parent().expect("has parent")).expect("mkdir");
                std::fs::write(path, content).expect("write");
            }
        }
    }
    if check && !stale.is_empty() {
        eprintln!(
            "out of date (run the generator without --check):\n  {}",
            stale.join("\n  ")
        );
        std::process::exit(1);
    }
    if !check {
        println!("{} files written, {} changed", files.len(), stale.len());
    }
}

/// Every type the app needs, with what it references.
fn definitions() -> Map<String, Value> {
    let mut generator = schemars::generate::SchemaSettings::draft2020_12().into_generator();
    let _ = generator.subschema_for::<ClientRequest>();
    let _ = generator.subschema_for::<ClientCommand>();
    let _ = generator.subschema_for::<ServerMessage>();
    let _ = generator.subschema_for::<ServerInfo>();
    let _ = generator.subschema_for::<SiteSummary>();
    let _ = generator.subschema_for::<PageResponse>();
    let _ = generator.subschema_for::<PutPageRequest>();
    let _ = generator.subschema_for::<PutPageResponse>();
    let _ = generator.subschema_for::<SearchHit>();
    let _ = generator.subschema_for::<AppMessage>();
    let _ = generator.subschema_for::<ProjectDiff>();
    let _ = generator.subschema_for::<ProjectOverview>();
    let _ = generator.subschema_for::<ChangedFile>();
    let _ = generator.subschema_for::<AgentSummary>();
    let _ = generator.subschema_for::<ProjectSummary>();
    let defs = generator.take_definitions(true);
    defs.into_iter().collect()
}

// ---------------------------------------------------------------- Dart code

fn generate(defs: &Map<String, Value>) -> String {
    let mut out = String::from(
        "// GENERATED by `cargo run -p composer-protocol --features schema --bin dartgen`. Do not edit.\n\
         // Source of truth: crates/protocol (Rust).\n\
         // ignore_for_file: annotate_overrides, prefer_const_constructors, unnecessary_this\n\n",
    );
    let sorted: BTreeMap<&String, &Value> = defs.iter().collect();
    for (name, schema) in sorted {
        let flattened = FLATTENED.iter().any(|(s, _, _)| s == name);
        let code = if flattened {
            struct_class(name, schema)
        } else if let Some(variants) = string_enum(schema) {
            enum_class(name, schema, &variants)
        } else if let Some((tag, variants)) = tagged_union(schema) {
            sealed_class(name, schema, &tag, &variants)
        } else {
            struct_class(name, schema)
        };
        out.push_str(&code);
        out.push('\n');
    }
    out.trim_end().to_string() + "\n"
}

/// `{"enum": [...]}` or a `oneOf` of string enums / consts.
fn string_enum(schema: &Value) -> Option<Vec<(String, Option<String>)>> {
    if let Some(values) = schema["enum"].as_array() {
        return Some(
            values
                .iter()
                .filter_map(|v| v.as_str().map(|s| (s.to_string(), None)))
                .collect(),
        );
    }
    let one_of = schema["oneOf"].as_array()?;
    let mut values = Vec::new();
    for option in one_of {
        if option["type"] != "string" {
            return None;
        }
        let doc = option["description"].as_str().map(str::to_string);
        if let Some(value) = option["const"].as_str() {
            values.push((value.to_string(), doc));
        } else {
            for value in option["enum"].as_array()? {
                values.push((value.as_str()?.to_string(), doc.clone()));
            }
        }
    }
    Some(values)
}

/// A `oneOf` of objects that each have one constant string property with the same name.
fn tagged_union(schema: &Value) -> Option<(String, Vec<Value>)> {
    let one_of = schema["oneOf"].as_array()?;
    let mut tag = None;
    for variant in one_of {
        let properties = variant["properties"].as_object()?;
        let (key, _) = properties.iter().find(|(_, p)| p["const"].is_string())?;
        if tag.get_or_insert_with(|| key.clone()) != key {
            return None;
        }
    }
    Some((tag?, one_of.clone()))
}

fn enum_class(name: &str, schema: &Value, values: &[(String, Option<String>)]) -> String {
    let mut out = doc(schema, "");
    writeln!(out, "enum {name} {{").unwrap();
    for (i, (value, value_doc)) in values.iter().enumerate() {
        if let Some(value_doc) = value_doc {
            writeln!(out, "  /// {}", value_doc.replace('\n', "\n  /// ")).unwrap();
        }
        let end = if i + 1 == values.len() { ";" } else { "," };
        writeln!(out, "  {}('{value}'){end}", camel(value)).unwrap();
    }
    writeln!(out, "\n  const {name}(this.wire);\n  final String wire;\n").unwrap();
    writeln!(
        out,
        "  static {name} fromJson(Object? json) =>\n      values.firstWhere((v) => v.wire == json, orElse: () => throw FormatException('unknown {name}: $json'));\n"
    )
    .unwrap();
    writeln!(out, "  String toJson() => wire;\n}}").unwrap();
    out
}

fn sealed_class(name: &str, schema: &Value, tag: &str, variants: &[Value]) -> String {
    let mut out = doc(schema, "");
    writeln!(out, "sealed class {name} {{\n  const {name}();\n").unwrap();
    writeln!(
        out,
        "  factory {name}.fromJson(Map<String, Object?> json) => switch (json['{tag}']) {{"
    )
    .unwrap();
    for variant in variants {
        let value = variant["properties"][tag]["const"]
            .as_str()
            .unwrap_or_default();
        writeln!(
            out,
            "        '{value}' => {}.fromJson(json),",
            variant_name(name, value)
        )
        .unwrap();
    }
    writeln!(
        out,
        "        _ => {name}Unknown(json),\n      }};\n\n  Map<String, Object?> toJson();\n}}\n"
    )
    .unwrap();

    for variant in variants {
        let value = variant["properties"][tag]["const"]
            .as_str()
            .unwrap_or_default();
        let class = variant_name(name, value);
        let fields = fields(variant, Some(tag));
        out.push_str(&class_body(
            &class,
            variant,
            &fields,
            Some((name, tag, value)),
        ));
        out.push('\n');
    }
    writeln!(
        out,
        "/// A `{tag}` this version doesn't know (a newer server): kept as raw JSON.\n\
         final class {name}Unknown extends {name} {{\n  const {name}Unknown(this.raw);\n  final Map<String, Object?> raw;\n\n  Map<String, Object?> toJson() => raw;\n}}"
    )
    .unwrap();
    out
}

fn struct_class(name: &str, schema: &Value) -> String {
    let mut fields = fields(schema, None);
    if let Some((_, field, union)) = FLATTENED.iter().find(|(s, _, _)| *s == name) {
        fields.push(Field {
            json: (*field).to_string(),
            dart: camel(field),
            ty: Type::Ref((*union).to_string()),
            required: true,
            nullable: false,
            doc: None,
            flattened: true,
        });
    }
    class_body(name, schema, &fields, None)
}

struct Field {
    json: String,
    dart: String,
    ty: Type,
    required: bool,
    nullable: bool,
    doc: Option<String>,
    /// `#[serde(flatten)]`: its JSON is merged into the parent object.
    flattened: bool,
}

#[derive(Clone)]
enum Type {
    String,
    Int,
    Double,
    Bool,
    Json,
    List(Box<Type>),
    Ref(String),
}

fn fields(schema: &Value, skip: Option<&str>) -> Vec<Field> {
    let required: Vec<&str> = schema["required"]
        .as_array()
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let Some(properties) = schema["properties"].as_object() else {
        return Vec::new();
    };
    properties
        .iter()
        .filter(|(key, _)| Some(key.as_str()) != skip)
        .map(|(key, property)| {
            let (ty, nullable) = parse_type(property);
            let is_required = required.contains(&key.as_str());
            Field {
                json: key.clone(),
                dart: camel(key),
                // Missing optional lists default to empty, other missing optionals to null.
                nullable: nullable
                    || (!is_required && !matches!(ty, Type::List(_)) && !has_zero(&ty)),
                required: is_required,
                ty,
                doc: property["description"].as_str().map(str::to_string),
                flattened: false,
            }
        })
        .collect()
}

/// `#[serde(default)]` numbers and bools are not required but never null.
fn has_zero(ty: &Type) -> bool {
    matches!(ty, Type::Int | Type::Double | Type::Bool)
}

fn parse_type(schema: &Value) -> (Type, bool) {
    if let Some(any_of) = schema["anyOf"].as_array() {
        let nullable = any_of.iter().any(|s| s["type"] == "null");
        let inner = any_of
            .iter()
            .find(|s| s["type"] != "null")
            .unwrap_or(&Value::Null);
        return (parse_type(inner).0, nullable);
    }
    if let Some(reference) = schema["$ref"].as_str() {
        return (
            Type::Ref(
                reference
                    .rsplit('/')
                    .next()
                    .unwrap_or(reference)
                    .to_string(),
            ),
            false,
        );
    }
    let (kind, nullable) = match &schema["type"] {
        Value::String(kind) => (kind.as_str(), false),
        Value::Array(kinds) => (
            kinds
                .iter()
                .filter_map(Value::as_str)
                .find(|k| *k != "null")
                .unwrap_or("null"),
            kinds.iter().any(|k| k == "null"),
        ),
        _ => return (Type::Json, true),
    };
    let ty = match kind {
        "string" => Type::String,
        "integer" => Type::Int,
        "number" => Type::Double,
        "boolean" => Type::Bool,
        "array" => Type::List(Box::new(parse_type(&schema["items"]).0)),
        _ => Type::Json,
    };
    (ty, nullable)
}

fn class_body(
    name: &str,
    schema: &Value,
    fields: &[Field],
    variant_of: Option<(&str, &str, &str)>,
) -> String {
    let mut out = doc(schema, "");
    match variant_of {
        Some((parent, _, _)) => writeln!(out, "final class {name} extends {parent} {{").unwrap(),
        None => writeln!(out, "class {name} {{").unwrap(),
    }
    // Constructor
    if fields.is_empty() {
        writeln!(out, "  const {name}();").unwrap();
    } else {
        writeln!(out, "  const {name}({{").unwrap();
        for f in fields {
            let default = match (&f.ty, f.nullable, f.required) {
                (_, true, _) | (_, _, true) => String::new(),
                (Type::List(_), _, _) => " = const []".into(),
                (Type::Int, _, _) => " = 0".into(),
                (Type::Double, _, _) => " = 0".into(),
                (Type::Bool, _, _) => " = false".into(),
                _ => String::new(),
            };
            let required = if !f.nullable && default.is_empty() {
                "required "
            } else {
                ""
            };
            writeln!(out, "    {required}this.{}{default},", f.dart).unwrap();
        }
        writeln!(out, "  }});").unwrap();
    }
    // Fields
    for f in fields {
        out.push('\n');
        if let Some(d) = &f.doc {
            writeln!(out, "  /// {}", d.replace('\n', "\n  /// ")).unwrap();
        }
        writeln!(
            out,
            "  final {}{} {};",
            dart_type(&f.ty),
            if f.nullable { "?" } else { "" },
            f.dart
        )
        .unwrap();
    }
    // fromJson
    writeln!(
        out,
        "\n  factory {name}.fromJson(Map<String, Object?> json) => {name}("
    )
    .unwrap();
    for f in fields {
        if f.flattened {
            // The enum's fields are the parent's own: parse the whole object.
            writeln!(
                out,
                "        {}: {}.fromJson(json),",
                f.dart,
                dart_type(&f.ty)
            )
            .unwrap();
            continue;
        }
        let source = format!("json['{}']", f.json);
        writeln!(
            out,
            "        {}: {},",
            f.dart,
            from_json(&f.ty, &source, f.nullable, f.required)
        )
        .unwrap();
    }
    writeln!(out, "      );\n").unwrap();
    // toJson: required fields always; optional ones only when set (Rust treats missing as None / empty).
    writeln!(out, "  Map<String, Object?> toJson() => {{").unwrap();
    if let Some((_, tag, value)) = variant_of {
        writeln!(out, "        '{tag}': '{value}',").unwrap();
    }
    for f in fields {
        let value = to_json(&f.ty, &f.dart, f.nullable);
        if f.flattened {
            writeln!(out, "        ...{}.toJson(),", f.dart).unwrap();
        } else if f.required {
            writeln!(out, "        '{}': {value},", f.json).unwrap();
        } else if f.nullable {
            writeln!(
                out,
                "        if ({} != null) '{}': {value},",
                f.dart, f.json
            )
            .unwrap();
        } else if matches!(f.ty, Type::List(_)) {
            writeln!(
                out,
                "        if ({}.isNotEmpty) '{}': {value},",
                f.dart, f.json
            )
            .unwrap();
        } else {
            writeln!(out, "        '{}': {value},", f.json).unwrap();
        }
    }
    writeln!(out, "      }};\n}}").unwrap();
    out
}

fn dart_type(ty: &Type) -> String {
    match ty {
        Type::String => "String".into(),
        Type::Int => "int".into(),
        Type::Double => "double".into(),
        Type::Bool => "bool".into(),
        Type::Json => "Object".into(),
        Type::List(item) => format!("List<{}>", dart_type(item)),
        Type::Ref(name) => name.clone(),
    }
}

fn from_json(ty: &Type, e: &str, nullable: bool, required: bool) -> String {
    let convert = |x: &str| match ty {
        Type::String => format!("{x} as String"),
        Type::Int => format!("({x} as num).toInt()"),
        Type::Double => format!("({x} as num).toDouble()"),
        Type::Bool => format!("{x} as bool"),
        Type::Json => format!("{x}!"),
        Type::Ref(name) if is_enum_ref(name) => format!("{name}.fromJson({x})"),
        Type::Ref(name) => format!("{name}.fromJson({x} as Map<String, Object?>)"),
        Type::List(item) => {
            format!(
                "({x} as List).map((e) => {}).toList()",
                from_json(item, "e", false, true)
            )
        }
    };
    if nullable {
        return match ty {
            Type::Json => e.to_string(),
            _ => format!("{e} == null ? null : {}", convert(e)),
        };
    }
    if !required {
        return match ty {
            Type::List(_) => format!("{e} == null ? const [] : {}", convert(e)),
            Type::Int | Type::Double => format!("{e} == null ? 0 : {}", convert(e)),
            Type::Bool => format!("{e} == null ? false : {}", convert(e)),
            _ => convert(e),
        };
    }
    convert(e)
}

fn to_json(ty: &Type, v: &str, nullable: bool) -> String {
    let q = if nullable { "?" } else { "" };
    match ty {
        Type::Ref(_) => format!("{v}{q}.toJson()"),
        Type::List(item) => match item.as_ref() {
            Type::Ref(_) | Type::List(_) => {
                format!("{v}{q}.map((e) => {}).toList()", to_json(item, "e", false))
            }
            _ => v.to_string(),
        },
        _ => v.to_string(),
    }
}

/// String enums are generated as Dart enums; everything else that is referenced is a class.
fn is_enum_ref(name: &str) -> bool {
    thread_local! {
        static ENUMS: Vec<String> = definitions().iter().filter(|(_, s)| string_enum(s).is_some()).map(|(n, _)| n.clone()).collect();
    }
    ENUMS.with(|enums| enums.iter().any(|e| e == name))
}

fn doc(schema: &Value, indent: &str) -> String {
    match schema["description"].as_str() {
        Some(d) => format!(
            "{indent}/// {}\n",
            d.replace('\n', &format!("\n{indent}/// "))
        ),
        None => String::new(),
    }
}

/// `turn.started` / `awaiting_approval` → `turnStarted` / `awaitingApproval`.
fn camel(value: &str) -> String {
    let pascal = pascal(value);
    let mut chars = pascal.chars();
    chars
        .next()
        .map(|c| c.to_lowercase().collect::<String>() + chars.as_str())
        .unwrap_or_default()
}

fn pascal(value: &str) -> String {
    value
        .split(['.', '_', '-'])
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut chars = p.chars();
            chars
                .next()
                .map(|c| c.to_uppercase().collect::<String>() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn variant_name(parent: &str, value: &str) -> String {
    format!("{parent}{}", pascal(value))
}

